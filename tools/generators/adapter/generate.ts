import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

function arg(name: string): string | undefined {
  const idx = process.argv.indexOf(`--${name}`);
  return idx >= 0 ? process.argv[idx + 1] : undefined;
}

